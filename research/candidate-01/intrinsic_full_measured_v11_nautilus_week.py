"""Full measured-auction portfolio, with NautilusTrader as sole engine.

This candidate combines three mutually exclusive responses:

1. A failed sweep aligned with 160-bps outer structure and opposite-flow
   takeover rotates to the nearest still-open opposing pivot.
2. A countertrend failed-sweep reversal which itself fails expands one accepted
   outside-excursion width beyond the failed-reversal path extreme.
3. A directional-change pivot which retained outside value and held its old
   boundary projects the accepted boundary-to-extreme range once beyond that
   extreme.

For measured expansions, structural invalidation is one economically derived
26-bps price-risk unit through the active acceptance boundary.  No target or
stop is selected from strategy PnL.  All fills, costs, margin and NAV are
exclusively generated by NautilusTrader on official Binance one-minute bars.
"""
