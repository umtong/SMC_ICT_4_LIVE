@dataclass(frozen=True, slots=True)
class StrategySpec:
    name: str
    module: str
    class_name: str
    branch: str | None = None


@dataclass(frozen=True, slots=True)
class RangeSpec:
    name: str
    build_start: str
    build_end: str
    evaluation_start: str
    evaluation_end: str
    calendar_days: int


