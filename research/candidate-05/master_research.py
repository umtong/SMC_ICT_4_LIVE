#!/usr/bin/env python3
"""Sequential evidence-driven Candidate 05 research orchestrator.

This is not a backtest engine.  Every experiment invokes ``candidate.py stage``;
NautilusTrader therefore remains the sole event replay, order matching, fill,
fee, position, margin, liquidation, accounting and NAV engine.  This module only
controls frozen ranges, strategy entrypoints, evidence classification and staged
promotion.
"""
